-- Натуральные ключи, на которых стоит идемпотентность импорта из Remnawave.
--
-- Импортёр не спрашивает «а есть ли уже такая строка» отдельным SELECT'ом: между
-- проверкой и вставкой есть гонка, а повторный прогон импорта — штатная операция
-- (сверил dry-run → применил → применил ещё раз после правки в панели). Поэтому
-- сопоставление держится на индексах.
--
-- config_profile (org_id, name): у нас 1 профиль = 1 нода (node_config_profile_uq),
-- значит профиль заводится на каждую ноду панели и находится по имени. Без индекса
-- второй прогон завёл бы профиль-двойник — и вместе с ним вторую ноду, потому что
-- старый профиль уже занят.
--
-- host (inbound_id, address, port): host — это endpoint «адрес:порт для этой
-- Reality-личности». Дубль не добавляет ничего, но в подписке превращается во второй
-- одинаковый канал (балансер начинает гонять пробы через один и тот же сервер дважды).
CREATE UNIQUE INDEX IF NOT EXISTS config_profile_org_name_uq ON "config_profile" ("org_id", "name");
CREATE UNIQUE INDEX IF NOT EXISTS host_inbound_address_port_uq ON "host" ("inbound_id", "address", "port");
