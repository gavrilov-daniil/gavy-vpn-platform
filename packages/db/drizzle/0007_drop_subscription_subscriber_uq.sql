-- Снимаем subscription_org_subscriber_uq (заведён миграцией 0006).
--
-- Ограничение «одна подписка на подписчика» не выдержало проверки реальными
-- данными: при импорте с действующей панели обнаружились аккаунты с двумя
-- подписками (вторая куплена для близких). Это законный сценарий, и терять
-- такие подписки при миграции нельзя.
--
-- Гонку параллельных /start по-прежнему гасит pg_advisory_xact_lock в
-- ensureSubscription: он не даёт создать вторую подписку автоматически.
-- Разница в том, что теперь несколько подписок — это осознанное состояние,
-- а не ошибка целостности.
DROP INDEX IF EXISTS subscription_org_subscriber_uq;
