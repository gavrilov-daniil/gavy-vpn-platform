-- Срок жизни bootstrap-токена ноды.
--
-- Выпущенный и невостребованный токен действовал вечно: распечатка из админки,
-- забытая в переписке полгода назад, оставалась рабочим обменом на per-node
-- agent-токен. Теперь у выпуска есть срок (NODE_BOOTSTRAP_TTL_HOURS, дефолт 24 ч),
-- и просроченный токен энроллмент не принимает.
--
-- NULL = без срока: так лежат токены, выпущенные до этой миграции, и выпуск при
-- явно выключенном TTL. Проверка в коде трактует NULL как «срока нет», а не как
-- «истёк»: иначе миграция разом обнулила бы доступ ещё не энролленным нодам.
ALTER TABLE "node_identity" ADD COLUMN IF NOT EXISTS "bootstrap_expires_at" timestamp with time zone;
